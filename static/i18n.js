// UI language: the switch in the header, else the browser's language.
const LANG = (() => {
  try {
    const l = localStorage.getItem("lang");
    if (l === "ja" || l === "en") return l;
  } catch {}
  return /^ja\b/i.test(navigator.language) ? "ja" : "en";
})();
document.documentElement.lang = LANG;

// t("日本語 {0}", x): the Japanese text is the key, EN has the English.
function t(ja, ...args) {
  let s = ja;
  if (LANG === "en") {
    s = EN[ja];
    if (s === undefined) {
      console.warn("i18n: no English for", ja);
      s = ja;
    }
  }
  return s.replace(/\{(\d+)\}/g, (_, i) => args[i]);
}
